package com.prototype.vulnwatch.client;

import java.util.UUID;
import java.util.regex.Pattern;

/** Customer identity checks shared by both AWS discovery pipelines. */
public final class AwsCustomerBinding {
    public static final int VERSION = 1;
    private static final Pattern ROLE = Pattern.compile("arn:(aws(?:-us-gov|-cn)?):iam::(\\d{12}):role/([A-Za-z0-9_+=,.@/-]{1,512})");
    private AwsCustomerBinding() { }

    public static String accountForRole(String roleArn) {
        var match = ROLE.matcher(roleArn == null ? "" : roleArn.trim());
        if (!match.matches() || match.group(3).endsWith("/")) {
            throw new IllegalArgumentException("A customer cross-account IAM role ARN is required");
        }
        return match.group(2);
    }

    public static void validate(UUID tenantId, String account, String role, String externalId, int bindingVersion) {
        if (account == null || !account.matches("\\d{12}") || !account.equals(accountForRole(role))) {
            throw new IllegalArgumentException("AWS role must belong to the configured customer account");
        }
        if (tenantId == null || bindingVersion != VERSION || externalId == null
                || !externalId.matches("scout-" + tenantId + "-[0-9a-f-]{36}")) {
            throw new IllegalArgumentException("AWS connector must be saved again to establish its server-generated External ID");
        }
    }

    public static String externalId(UUID tenantId, String existing, int version, String supplied) {
        if (tenantId == null) throw new IllegalArgumentException("AWS customer tenant is required");
        if (supplied != null && !supplied.isBlank() && (version != VERSION || !supplied.equals(existing))) {
            throw new IllegalArgumentException("External ID is generated by the server and cannot be supplied or replaced");
        }
        return version == VERSION && existing != null ? existing : "scout-" + tenantId + "-" + UUID.randomUUID();
    }

    public static void verifyIdentity(String account, String role, String actualAccount, String actualArn) {
        String expectedAccount = accountForRole(role);
        String partition = role.split(":", 3)[1];
        String roleName = role.substring(role.lastIndexOf('/') + 1);
        String expectedArn = "arn:" + partition + ":sts::" + expectedAccount + ":assumed-role/" + roleName + "/";
        if (!expectedAccount.equals(account) || !account.equals(actualAccount)
                || actualArn == null || !actualArn.startsWith(expectedArn) || actualArn.length() <= expectedArn.length()) {
            throw new IllegalStateException("Effective AWS identity does not match the configured customer role and account");
        }
    }
}
